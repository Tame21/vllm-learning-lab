export async function runObservationDepthBrowserRegressions(tab) {
  const page = tab.playwright || tab, results = [];
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const open = (id) => page.locator(`.lesson-nav button[data-lesson="${id}"]`).click();
  const last = () => page.getByLabel('执行时间轴').press('End');
  const first = () => page.getByLabel('执行时间轴').press('Home');
  const advance = async (n) => { for (let i = 0; i < n; i++) await page.getByLabel('执行时间轴').press('ArrowRight'); };
  await open('scheduler'); await page.getByRole('button', { name: '默认', exact: true }).click();
  await first(); await advance(4);
  check((await page.locator('.depth-phases .current').innerText()) === '执行', '调度可暂停在写入与采样之间');
  await page.getByRole('button', { name: '第 2 轮请求 A', exact: true }).click();
  check((await page.locator('.scene-caption').innerText()).includes('第 2 轮'), '轮次按钮映射结算帧');
  results.push('调度准入、分配、执行、采样与轮次跳转');
  await open('chunked'); await page.getByRole('button', { name: '默认', exact: true }).click(); await last();
  const sync = await page.getByRole('table', { name: '切块同步轮次对照' }).innerText();
  check(sync.includes('停滞 · 未完成') && sync.includes('开启切块'), '同步对照保留未完成状态');
  results.push('切块开关同步轮次与停滞边界');
  await open('paged'); await first(); await advance(8);
  const address = await page.getByLabel('当前 KV 地址').innerText();
  check(address.includes('写 token 6') && address.includes('物理块 5') && address.includes('slot 22'), '逐 token KV 地址链');
  results.push('KV 逐 token 逻辑块、物理块与 slot');
  await open('prefix'); await last();
  check((await page.getByRole('table', { name: '前缀整块查找' }).locator('tbody tr').count()) === 3, '逐块查询记录完整');
  check((await page.locator('#scene').innerText()).includes('末尾 logits：已计算'), '末尾 logits 保留');
  results.push('前缀整块查询、引用与末尾 logits');
  await open('speculative'); await page.getByLabel('草稿分布接近目标的程度').press('Home'); await first(); await advance(2);
  check((await page.locator('.spec-result').innerText()).includes('等待接受与恢复'), '验证前不提交');
  await last();
  check((await page.locator('.spec-lane .rejected').count()) === 1 && (await page.locator('.spec-lane .discarded').count()) > 0, '首拒绝后同步丢弃后缀');
  results.push('逐位置接受、拒绝、后缀丢弃与恢复');
  await open('tp'); await first(); await advance(1);
  check((await page.getByRole('table', { name: '逐列局部乘法' }).innerText()).includes('1/'), '部分和逐列推进'); await last();
  check((await page.locator('.depth-address').innerText()).includes('归并累计'), '通信贡献归并');
  results.push('TP 局部乘积、部分和与归并贡献');
  await open('pp'); await page.getByLabel('流水线段数').press('End'); await page.getByLabel('独立 microbatch 数').press('Home'); await last();
  check((await page.locator('#scene').innerText()).includes('没有满流水线稳态'), '短批次没有虚构稳态');
  results.push('PP 稳定身份、交接与无稳态边界');
  await open('moe'); await first(); await advance(1);
  const routing = page.getByRole('table', { name: 'Token 路由身份' });
  check((await routing.innerText()).includes('等待分发'), '未分发 token 保留等待'); await last();
  check((await routing.locator('tbody tr').allTextContents()).every((row) => row.includes('已返回')), '每个 token 返回原 rank');
  results.push('MoE 逐 token 分发与加权返回');
  await open('structured'); await page.getByLabel('字符串值（0 vLLM / 1 模型）').press('End'); await last();
  check((await page.locator('#scene').innerText()).includes('{"name":"模型"}') && (await page.locator('.grammar-candidates .generated').innerText()) === 'EOS', '合法字符串参数与终态允许集合');
  results.push('JSON 语法状态、合法值与允许集合');
  await open('offload'); await page.getByRole('button', { name: '三层小容量 / 回载', exact: true }).click(); await last();
  check((await page.locator('.device-tier.cpu .ready').count()) <= 1 && (await page.locator('.device-tier.external .ready').count()) <= 1, '三层容量约束');
  check((await page.locator('#scene').innerText()).includes('外部回载完成'), '外部回载可观察');
  results.push('三层缓存容量、淘汰与外部回载');
  await open('disagg'); await page.getByRole('button', { name: '传输失败阻塞', exact: true }).click(); await last();
  const rows = await page.getByRole('table', { name: '单实例与分离依赖对照' }).locator('tbody tr').allTextContents();
  check(rows[0].includes('有效') && rows[1].includes('等待确认'), '失败分离不影响单实例');
  results.push('单实例与分离部署的同请求依赖对照');
  return results;
}
