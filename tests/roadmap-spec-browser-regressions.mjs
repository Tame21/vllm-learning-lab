export async function runRoadmapSpecBrowserRegressions(tab) {
  const page = tab.playwright || tab, results = [];
  const check = (v, m) => { if (!v) throw Error(m); };
  const open = (id) => page.locator(`.lesson-nav button[data-lesson="${id}"]`).click();
  const preset = (name) => page.getByRole('button', { name, exact: true }).click();
  const last = () => page.getByLabel('执行时间轴').press('End');
  const text = () => page.locator('.mechanism-scene').innerText();
  await open('ngram'); await preset('重复后缀');
  await page.getByLabel('请求 A 的 token 历史', { exact: true }).fill('X Y Z X Y');
  await page.getByLabel('请求 A 的 token 历史', { exact: true }).press('Enter'); await last();
  check((await page.getByRole('table', { name: 'N-gram 候选与有效长度' }).innerText()).includes('Z X Y'), '历史编辑实际计算新候选');
  await tab.reload();
  check((await page.getByLabel('请求 A 的 token 历史', { exact: true }).getAttribute('value')) === 'X Y Z X Y', '文本历史刷新恢复');
  await page.getByLabel('请求 A 的 token 历史', { exact: true }).fill('<bad>'); await page.getByLabel('请求 A 的 token 历史', { exact: true }).press('Enter');
  check((await page.locator('#parameter-error').innerText()).includes('短 token'), '非法输入可见反馈');
  await preset('没有历史匹配'); await last(); check((await text()).includes('无草稿，目标正常生成'), '无匹配走目标路径');
  results.push('可编辑 N-gram、刷新恢复、非法输入与无匹配');
  await open('ngram-gpu'); await preset('不同有效长度'); await last();
  check((await page.getByRole('table', { name: 'N-gram 候选与有效长度' }).innerText()).includes('-1'), 'GPU 有效长度与 padding');
  await preset('屏蔽请求 B'); await last();
  check((await page.getByRole('table', { name: 'N-gram 候选与有效长度' }).locator('tbody tr').last().innerText()).includes('[-1, -1, -1]'), '屏蔽行全无效');
  results.push('多请求 N-gram 候选张量和行屏蔽');
  await open('suffix'); await preset('频次树续写'); await last();
  check((await page.locator('[data-visual-key^="suffix-path-"]').count()) === 3, '频次路径有三个候选');
  await preset('高门限停止'); await last(); check((await page.locator('[data-visual-key^="suffix-path-"]').count()) === 1, '条件频率门限停止');
  results.push('后缀频次出边与门限停止');
  await open('draft-model'); await preset('更长候选链'); await last();
  check((await page.getByRole('table', { name: '串行草稿输入与递推' }).locator('tbody tr').count()) === 5, '串行五次前向');
  await preset('全收与 bonus'); await last(); check((await page.locator('[data-visual-key="spec-gate"]').innerText()).includes('BONUS'), '全收追加 bonus');
  results.push('串行前向、草稿 KV、逐位置验证和 bonus');
  await open('eagle'); await preset('隐藏状态对齐'); await last();
  const eagleBefore = await page.getByRole('table', { name: '串行草稿输入与递推' }).innerText();
  await preset('改变隐藏特征'); await last(); check(eagleBefore !== await page.getByRole('table', { name: '串行草稿输入与递推' }).innerText(), '隐藏特征改变递推');
  results.push('EAGLE token / position / hidden 对齐');
  await open('eagle3'); await preset('三层特征拼接'); await last(); check((await text()).includes('拼接宽度 6'), '三层辅助特征');
  await preset('单层对照'); await last(); check((await text()).includes('拼接宽度 2'), '单层形状变化');
  results.push('EAGLE3 辅助层形状对照');
  await open('mtp'); await preset('匹配模型 / 索引复用'); await last(); check((await text()).includes('复用首轮索引'), 'MTP 条件索引共享');
  await preset('关闭索引复用'); await last(); check(!(await page.getByRole('table', { name: '串行草稿输入与递推' }).innerText()).includes('复用首轮索引'), '不匹配接口时重算');
  results.push('MTP 匹配接口的索引共享分支');
  await open('mlp-spec'); await preset('级联输入图解'); await last(); check((await page.locator('[data-visual-key="spec-gate"]').innerText()).includes('禁止执行'), 'MLP 保留阻止状态');
  check((await page.locator('[data-spec-command]').count()) === 0, '未注册模型没有运行模板');
  results.push('MLP 级联观察和未接入边界');
  await open('medusa'); await preset('共享隐藏状态扇出'); await last(); check((await page.getByRole('table', { name: '并行草稿位置与采样依赖' }).innerText()).includes('无前一候选依赖'), 'Medusa 共享头依赖');
  results.push('Medusa 同一隐藏状态多头扇出');
  await open('parallel-draft'); await preset('模型配置不匹配'); await last(); check((await page.locator('[data-visual-key="spec-gate"]').innerText()).includes('不匹配'), 'PARD 配置门禁');
  await preset('并行查询块'); await last(); check((await page.locator('[data-visual-key^="spec-query-"]').count()) === 3, 'PARD K 查询布局');
  results.push('PARD 单前向位置与模型配置校验');
  await open('dflash'); await preset('上下文与 mask 查询'); await last(); check((await page.locator('[data-visual-key^="spec-query-"]').count()) === 4, 'DFlash 1+K 查询');
  await preset('较长上下文'); await last(); check((await page.locator('[data-visual-key^="spec-context-"]').count()) === 8, '上下文 KV 长度实际变化');
  results.push('DFlash KV 与 anchor / mask 分离');
  await open('dspark'); await preset('Markov 顺序依赖'); await last();
  const markov = await page.getByRole('table', { name: '并行草稿位置与采样依赖' }).innerText();
  check((await page.locator('[data-visual-key^="spec-query-"]').count()) === 3, 'DSpark 默认 K 查询');
  await preset('关闭 Markov 偏置'); await last(); check(markov !== await page.getByRole('table', { name: '并行草稿位置与采样依赖' }).innerText(), 'Markov 偏置改变候选');
  await preset('1+K 填充布局'); await last(); check((await page.locator('[data-visual-key^="spec-query-"]').count()) === 4, 'DSpark 配置切换查询布局');
  results.push('DSpark 两种查询布局与顺序 Markov 候选');
  return results;
}
