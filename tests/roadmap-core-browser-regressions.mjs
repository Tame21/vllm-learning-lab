export async function runRoadmapCoreBrowserRegressions(tab) {
  const page = tab.playwright || tab, results = [];
  const check = (value, message) => { if (!value) throw Error(message); };
  const open = (id) => page.locator(`.lesson-nav button[data-lesson="${id}"]`).click();
  const preset = (name) => page.getByRole('button', { name, exact: true }).click();
  const last = () => page.getByLabel('执行时间轴').press('End');
  const text = () => page.locator('.mechanism-scene').innerText();
  await open('prefill'); await preset('多轮 Decode'); await last();
  check((await page.getByRole('table', { name: 'Prefill Decode KV 增长' }).locator('tbody tr').count()) === 7, '多轮 Decode 的 KV 增长');
  check((await text()).includes('203 · KV 未写'), '最后输出尚未写 KV');
  await preset('第一枚输出即 EOS'); await last();
  check((await text()).includes('EOS 停止') && (await page.getByRole('table', { name: 'Prefill Decode KV 增长' }).locator('tbody tr').count()) === 5, 'EOS 不执行后续前向');
  results.push('Prefill / Decode 多轮 QKV、缓存增长与 EOS');
  await open('sampling'); await preset('随机采样'); await last();
  check((await page.locator('.roadmap-probabilities .selected').count()) === 1, '实际采样结果高亮');
  await preset('贪心 T=0'); await last();
  check((await text()).includes('贪心跳过') && (await text()).includes('贪心分支不使用 Top-p 和随机数'), '贪心不执行随机抽样');
  await page.getByRole('tab', { name: '对应源码', exact: true }).click();
  check((await page.locator('.source-anchor').innerText()).includes('greedy_sample'), '贪心源码分支同步');
  results.push('温度、Top-p、指数竞赛与贪心源码');
  await open('quantization'); await preset('INT4 打包'); await last();
  check((await page.locator('.roadmap-bytes>div').count()) === 4, '八个 INT4 元素打包四字节');
  await preset('INT8 编码'); await last();
  check((await page.locator('.roadmap-bytes>div').count()) === 8, 'INT8 一元素一字节');
  results.push('整数缩放、舍入、补码打包与解包');
  await open('cp'); await preset('DCP / LSE 合并'); await last();
  check((await page.getByRole('table', { name: '上下文并行局部结果' }).locator('tbody tr').count()) === 2, 'DCP 两片局部结果');
  await preset('PCP 早期 query'); await last();
  check((await page.getByRole('table', { name: '上下文并行局部结果' }).locator('tbody tr').count()) === 1 && (await text()).includes('query 1'), 'PCP Gather 后所属 rank 计算');
  results.push('PCP KV Gather 与 DCP LSE 归并');
  await open('eplb'); await preset('热点专家复制'); await last();
  check((await page.locator('[data-visual-key="eplb-gate"]').innerText()).includes('映射切换已完成'), '目标副本确认后映射切换');
  check((await page.locator('.roadmap-expert-layout').last().locator('.ready').count()) === 6, '六个物理专家目标就绪');
  results.push('EPLB 热点副本、目标权重确认与映射版本');
  await open('lora'); await preset('混合适配器批次'); await last();
  const before = await page.getByRole('table', { name: '混合 LoRA 请求计算' }).innerText();
  await preset('反转行顺序'); await last();
  check((await page.getByRole('table', { name: '混合 LoRA 请求计算' }).innerText()) !== before, '行顺序可改变');
  await preset('零增量对照'); await last();
  check((await text()).includes('增量比例 0'), '零增量回到共享基础输出');
  results.push('混合 LoRA 逐行映射、行重排与 base 对照');
  await open('multimodal'); await preset('重复图像 / 缓存命中'); await last();
  check((await page.locator('[data-visual-key="mm-gate"]').innerText()).includes('完整模型输入已对齐'), '特征按占位对齐');
  check((await text()).includes('缓存命中'), '重复媒体缓存命中');
  await preset('占位数量不匹配'); await last();
  check((await page.locator('[data-visual-key="mm-gate"]').innerText()).includes('禁止前向'), '不匹配阻止前向');
  results.push('多模态特征、重复媒体缓存与占位数量校验');
  return results;
}
